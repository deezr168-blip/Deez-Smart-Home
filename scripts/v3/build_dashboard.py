#!/usr/bin/env python3
"""CasaRay V3 build.  DEVELOPMENT ONLY — NOT DEPLOYED.

    python3 scripts/v3/build_dashboard.py            # write every locale
    python3 scripts/v3/build_dashboard.py --check    # exit 1 if outputs are stale

Deterministic: same sources -> byte-identical outputs (no timestamps, sorted
nothing that has meaning by order, fixed YAML dump settings). Reads only
files in this repository; never touches Home Assistant.

Inputs  src/casaray_v3/{manifest.yaml, i18n/*.yaml, views/*.yaml}
        (outside dashboards/ on purpose: the repo gate treats every YAML there
        as a live dashboard)
        dashboards/casaray_v2.yaml (baseline, SHA-256 pinned in the manifest)
        docs/live/states_export_2026-09-05.txt (entity authority)
Outputs per-locale dashboards (see manifest), docs/casaray-v3/build_report.json,
        docs/casaray-v3/VIEW_INVENTORY.md, docs/casaray-v3/ENTITY_MATRIX.md
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import components as C  # noqa: E402

SRC = ROOT / "src" / "casaray_v3"
DOCS = ROOT / "docs" / "casaray-v3"

HEADER = """\
# ============================================================================
# CasaRay V3 — {locale_name}
# GENERATED by scripts/v3/build_dashboard.py — DO NOT EDIT BY HAND.
# DEVELOPMENT ONLY — NOT DEPLOYED. Not registered in Home Assistant.
# Sources: src/casaray_v3/  ·  url_path: {url_base}
# Baseline: {baseline_file} sha256 {baseline_sha}
# ============================================================================
"""

ENTITY_RX = re.compile(
    r"\b(?:light|switch|scene|climate|camera|sensor|binary_sensor|person|input_boolean|"
    r"input_number|input_select|input_datetime|input_text|input_button|fan|media_player|"
    r"weather|zone|todo|button|siren|alarm_control_panel|cover|lock|update|device_tracker|"
    r"select|number|script|automation|event|counter|calendar|sun|vacuum|remote|image|"
    r"water_heater|valve)\.[a-z0-9_]+\b")
ACTION_KEYS = {"action", "perform_action", "service"}


# ------------------------------------------------------------------ loading

class T(str):
    """A localised-string key. Sources write it as `{t: key}` (plain YAML, so
    every repository YAML gate can parse the sources)."""


class DupKeyLoader(yaml.SafeLoader):
    pass


def _no_dups(loader, node, deep=False):
    seen = set()
    for k, _ in node.value:
        key = loader.construct_object(k, deep=deep)
        if key in seen:
            raise yaml.constructor.ConstructorError(
                None, None, f"duplicate key {key!r}", k.start_mark)
        seen.add(key)
    return yaml.SafeLoader.construct_mapping(loader, node, deep)


DupKeyLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _no_dups)


def load_yaml(path, loader=DupKeyLoader):
    with open(path, encoding="utf-8") as fh:
        return yaml.load(fh, Loader=loader)


def load_export(path):
    ex = {}
    with open(path, encoding="utf-8") as fh:
        lines = fh.readlines()
    for line in lines:
        parts = line.rstrip("\n").split("|")
        if len(parts) >= 4 and "." in parts[0]:
            ex[parts[0]] = {"name": parts[1], "area": parts[2], "availability": parts[3]}
    return ex


# ------------------------------------------------------------------ dumping

class Dumper(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _str(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", str(data), style=style)


Dumper.add_representer(str, _str)
Dumper.add_representer(T, _str)


def dump(obj):
    return yaml.dump(obj, Dumper=Dumper, sort_keys=False, allow_unicode=True,
                     width=4096, default_flow_style=False)


# ------------------------------------------------------------------ context

class Ctx:
    def __init__(self, locale, catalogues, export, url_base):
        self.locale = locale
        self.cats = catalogues
        self.export = export
        self.url_base = url_base
        self.fallbacks = set()
        self.missing = set()
        self.used = set()

    def t(self, key):
        chain = [self.locale["code"]] + list(self.locale.get("fallback", [])) + ["en"]
        for i, code in enumerate(chain):
            cat = self.cats.get(code, {})
            if key in cat:
                if i:
                    self.fallbacks.add(key)
                return str(cat[key])
        self.missing.add(key)
        return key

    def jt(self, key, **exprs):
        """A localised string as a Jinja expression, {name} -> (expr)."""
        s = self.t(key)
        parts, pos = [], 0
        for m in re.finditer(r"\{(\w+)\}", s):
            if m.start() > pos:
                parts.append(C.jstr(s[pos:m.start()]))
            parts.append("(" + exprs[m.group(1)] + ")")
            pos = m.end()
        if pos < len(s):
            parts.append(C.jstr(s[pos:]))
        return " ~ ".join(parts) if parts else '""'

    def link(self, path):
        return f"/{self.url_base}/{path}"

    def use(self, ents):
        for e in ([ents] if isinstance(ents, str) else ents):
            self.used.add(e)

    def friendly(self, eid):
        return self.export.get(eid, {}).get("name", eid)


def resolve(node, ctx):
    """Expand `!t` strings and `{c: component, ...}` calls, depth-first."""
    if isinstance(node, T):
        return ctx.t(str(node))
    if isinstance(node, dict) and set(node) == {"t"}:
        return ctx.t(str(node["t"]))
    if isinstance(node, list):
        out = []
        for item in node:
            r = resolve(item, ctx)
            if isinstance(item, dict) and "c" in item and isinstance(r, list):
                out.extend(r)
            else:
                out.append(r)
        return out
    if isinstance(node, dict):
        if "c" in node:
            fn = getattr(C, node["c"])
            kwargs = {k: resolve(v, ctx) for k, v in node.items() if k != "c"}
            return fn(ctx, **kwargs)
        return {k: resolve(v, ctx) for k, v in node.items()}
    return node


def build_native(spec, ctx):
    view = {"title": ctx.t(spec["title"]), "path": spec["path"], "icon": spec["icon"],
            "type": "sections", "max_columns": 2, "theme": ctx.theme}
    if spec.get("subview"):
        view["subview"] = True
    sections = []
    for sec in spec["sections"]:
        if sec.get("topbar"):
            sections.append(C.topbar(ctx, spec["path"], spec["title"]))
            continue
        if "c" in sec:
            sections.append(resolve(sec, ctx))
            continue
        cards = []
        if sec.get("heading"):
            cards.append(C.heading(ctx, sec["heading"]))
        cards.extend(resolve(sec.get("cards", []), ctx))
        sections.append({"type": "grid", "column_span": sec.get("span", 1), "cards": cards})
    view["sections"] = sections
    return view


def rewrite_links(node, old, new):
    if isinstance(node, str):
        return node.replace(f"/{old}/", f"/{new}/")
    if isinstance(node, list):
        return [rewrite_links(x, old, new) for x in node]
    if isinstance(node, dict):
        return {k: rewrite_links(v, old, new) for k, v in node.items()}
    return node


def entities_in(node, out=None, key=None):
    out = set() if out is None else out
    if isinstance(node, str):
        if key not in ACTION_KEYS:
            out.update(m.group(0) for m in ENTITY_RX.finditer(node))
    elif isinstance(node, list):
        for x in node:
            entities_in(x, out, key)
    elif isinstance(node, dict):
        for k, v in node.items():
            entities_in(v, out, k)
    return out


# ------------------------------------------------------------------ build

def build(write=True):
    man = load_yaml(SRC / "manifest.yaml")
    base = man["baseline"]
    v2_path = ROOT / base["file"]
    v2_raw = v2_path.read_bytes()
    sha = hashlib.sha256(v2_raw).hexdigest()
    if sha != base["sha256"]:
        raise SystemExit(f"BASELINE DRIFT: {base['file']} sha256 {sha} != pinned {base['sha256']}")
    v2 = yaml.safe_load(v2_raw)
    export = load_export(ROOT / man["entity_authority"])
    cats = {p.stem: load_yaml(p) for p in sorted((SRC / "i18n").glob("*.yaml"))}
    specs = {}
    for p in sorted((SRC / "views").glob("*.yaml")):
        s = load_yaml(p)
        specs[s["path"]] = s
    for n in man["native"]:
        if n not in specs:
            raise SystemExit(f"native view {n!r} has no source in src/casaray_v3/views/")

    v2_views = v2["views"]
    v2_paths = [v["path"] for v in v2_views]
    outputs, report = {}, {"baseline": {"file": base["file"], "sha256": sha, "ref": base["ref"]},
                           "locales": {}, "views": []}

    for li, loc in enumerate(man["locales"]):
        ctx = Ctx(loc, cats, export, loc["url_base"])
        ctx.theme = man["theme"]
        views, rows = [], []
        for v in v2_views:
            p = v["path"]
            if p in man["native"]:
                ctx.used = set()
                nv = build_native(specs[p], ctx)
                views.append(nv)
                rows.append({"path": p, "kind": "native", "source": f"views/{p}.yaml",
                             "v2_equivalent": p, "entities": sorted(entities_in(nv))})
            else:
                cv = rewrite_links(copy.deepcopy(v), base["url_base"], loc["url_base"])
                cv["theme"] = man["classic_theme"]
                views.append(cv)
                rows.append({"path": p, "kind": "carried", "source": f"{base['file']}#{p}",
                             "v2_equivalent": p, "entities": sorted(entities_in(cv))})
        for p in man["native"]:  # classic copies of every rebuilt V2 view
            v = v2_views[v2_paths.index(p)]
            cv = rewrite_links(copy.deepcopy(v), base["url_base"], loc["url_base"])
            cv["path"], cv["subview"], cv["theme"] = f"v2-{p}", True, man["classic_theme"]
            cv["title"] = f"{v.get('title', p)} (V2)"
            views.append(cv)
            rows.append({"path": f"v2-{p}", "kind": "classic", "source": f"{base['file']}#{p}",
                         "v2_equivalent": p, "entities": sorted(entities_in(cv))})
        dash = {"title": f"CasaRay V3 ({loc['code']})", "views": views}
        text = HEADER.format(locale_name=loc["name"], url_base=loc["url_base"],
                             baseline_file=base["file"], baseline_sha=sha) + dump(dash)
        outputs[loc["output"]] = text
        report["locales"][loc["code"]] = {
            "output": loc["output"], "url_base": loc["url_base"],
            "fallback_keys": sorted(ctx.fallbacks), "missing_keys": sorted(ctx.missing),
            "views": len(views)}
        if li == 0:
            for r in rows:
                v2e = set()
                if r["kind"] == "native":
                    v2e = entities_in(v2_views[v2_paths.index(r["path"])])
                ents = r["entities"]
                r["unverified"] = sorted(e for e in ents if e not in export)
                r["dark_at_export"] = sorted(e for e in ents if e in export
                                             and export[e]["availability"] != "ok")
                if r["kind"] == "native":
                    r["v2_entities_not_on_native"] = sorted(v2e - set(ents) - {"input_boolean.chinese_dashboard"})
                report["views"].append(r)
            for r in report["views"]:
                if r["kind"] == "native":
                    v2e = entities_in(v2_views[v2_paths.index(r["path"])]) - {"input_boolean.chinese_dashboard"}
                    r["migration"] = check_migration(r["path"], v2e, man.get("migration", {}).get(r["path"], {}),
                                                     report["views"], export)

    outputs[str(DOCS.relative_to(ROOT) / "build_report.json")] = json.dumps(
        report, indent=2, ensure_ascii=False, sort_keys=False) + "\n"
    outputs[str(DOCS.relative_to(ROOT) / "VIEW_INVENTORY.md")] = view_inventory(report)
    outputs[str(DOCS.relative_to(ROOT) / "ENTITY_MATRIX.md")] = entity_matrix(report, export)

    stale = []
    for rel, text in outputs.items():
        path = ROOT / rel
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(rel)
            if write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    return outputs, report, stale


STATUSES = {"native", "carried", "retained", "blocked"}
DESTINATIONS = {  # view path -> household destination name, for the inventory
    "home": "Home", "lighting": "Lighting", "climate": "Climate", "energy": "Energy",
    "cameras": "Cameras", "security": "Security", "network": "Network",
    "house-health": "House health", "alerts": "Alerts", "bills": "Bills", "bills-details": "Bills",
    "people": "People", "automations": "Automations", "entertainment": "Entertainment",
    **{p: "Rooms" for p in ("rooms", "living-room", "kitchen", "dining", "parents-room",
                            "ray-bedroom", "garage", "guest-room")},
}


def destination(path):
    if path.startswith("camera-"):
        return "Cameras"
    return DESTINATIONS.get(path, path)


def check_migration(native_path, v2_entities, declared, views, export):
    """Verify every row of manifest `migration.<native_path>` against the
    generated views, and that no V2 entity of the rebuilt view is unaccounted
    for. Any false, stale or missing row stops the build."""
    by_path = {r["path"]: r for r in views}
    on_native = set(by_path[native_path]["entities"])
    errors, rows = [], []
    for e in sorted((v2_entities - on_native) - set(declared)):
        errors.append(f"{e}: on V2 {native_path} but neither on the native rebuild nor in "
                      f"manifest migration.{native_path}")
    for e, d in sorted(declared.items()):
        # An unquoted comma in a flow-mapping note silently becomes a new key.
        extra = sorted(set(d) - {"to", "status", "note"})
        if extra:
            errors.append(f"{e}: unknown keys {extra} (quote a note that contains a comma)")
        to, status, note = d.get("to"), d.get("status"), str(d.get("note", "")).strip()
        if e not in v2_entities:
            errors.append(f"{e}: declared but not on V2 {native_path} (stale row)")
        if status not in STATUSES:
            errors.append(f"{e}: status {status!r} is not one of {sorted(STATUSES)}")
        elif status in ("native", "carried"):
            tv = by_path.get(to)
            if tv is None:
                errors.append(f"{e}: destination {to!r} is not a V3 view")
            elif tv["kind"] != status:
                errors.append(f"{e}: says {status} on {to}, but {to} is {tv['kind']}")
            elif e not in tv["entities"]:
                errors.append(f"{e}: says it is on {to}, but {to} does not reference it")
        else:
            if not note:
                errors.append(f"{e}: {status} needs a reason in `note`")
            if e in on_native:
                errors.append(f"{e}: says {status}, but it is on the native {native_path} view")
        also = sorted(r["path"] for r in views if r["kind"] != "classic" and e in r["entities"]
                      and r["path"] not in (to, native_path))
        rows.append({"entity": e, "name": export.get(e, {}).get("name", ""), "to": to,
                     "destination": destination(to) if to else "", "status": status,
                     "also_on": also, "note": note})
    if errors:
        raise SystemExit("MIGRATION MAP WRONG:\n  " + "\n  ".join(errors))
    return rows


GEN = "<!-- GENERATED by scripts/v3/build_dashboard.py — do not edit. DEVELOPMENT ONLY — NOT DEPLOYED. -->\n\n"


def view_inventory(rep):
    lines = [GEN + "# CasaRay V3 — view inventory\n",
             "Every V2 view has a V3 home. `native` = rebuilt from `src/casaray_v3/views/`; "
             "`carried` = the V2 view verbatim, links rewritten to the V3 url_path, still on the "
             "`CasaRay` theme and the V2 `input_boolean.chinese_dashboard` toggle; `classic` = the "
             "original V2 view kept as a `v2-<path>` subview beside its native rebuild, so no V2 "
             "function is lost while the rebuild matures.\n",
             f"Baseline: `{rep['baseline']['file']}` {rep['baseline']['ref']} sha256 "
             f"`{rep['baseline']['sha256']}`\n",
             "| # | Path | Kind | Source | Entities | Not in export | Dark at 05/09 export |",
             "|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rep["views"], 1):
        lines.append(f"| {i} | `{r['path']}` | {r['kind']} | `{r['source']}` | {len(r['entities'])} | "
                     f"{len(r['unverified']) or '—'} | {len(r['dark_at_export']) or '—'} |")
    lines.append("\n## Native rebuilds: where every V2 entity now lives\n")
    lines.append("For each rebuilt view, every V2 entity that is not on the rebuild itself, or that "
                 "the migration moved onto it, with its destination and coverage. Source: "
                 "`src/casaray_v3/manifest.yaml` `migration`; the build checks every row against "
                 "the generated dashboard and refuses to run on a false or missing one. "
                 "`native` = on a V3-native view; `carried` = on a carried V2 board, so it still "
                 "renders as V2 until that board is rebuilt; `retained` / `blocked` = only on the "
                 "classic `v2-<path>` subview, for the reason given. Every entity also stays on "
                 "its classic subview, linked from the native view's More boards band, until "
                 "native parity is verified on a device.\n")
    for r in rep["views"]:
        if r["kind"] != "native":
            continue
        mig = r.get("migration", [])
        counts = {s: sum(1 for m in mig if m["status"] == s) for s in ("native", "carried", "retained", "blocked")}
        summary = ", ".join(f"{n} {s}" for s, n in counts.items() if n) or "none"
        lines.append(f"### {r['path']} ({len(mig)}: {summary})\n")
        if not mig:
            lines.append("Every V2 entity of this view is on its native rebuild.\n")
            continue
        lines.append("| Entity | Friendly name (export) | Destination | Coverage | Also on | Note |")
        lines.append("|---|---|---|---|---|---|")
        for m in mig:
            dest = f"{m['destination']} · `{m['to']}`" if m["to"] else "—"
            also = ", ".join(f"`{a}`" for a in m["also_on"]) or "—"
            lines.append(f"| `{m['entity']}` | {m['name'] or '—'} | {dest} | {m['status']} | {also} | {m['note'] or '—'} |")
        lines.append("")
    lines.append("\n## Locales\n")
    lines.append("| Locale | Output | url_path | Views | Keys on fallback | Missing keys |")
    lines.append("|---|---|---|---|---|---|")
    for code, l in rep["locales"].items():
        lines.append(f"| {code} | `{l['output']}` | `/{l['url_base']}` | {l['views']} | "
                     f"{len(l['fallback_keys'])} | {len(l['missing_keys'])} |")
    return "\n".join(lines) + "\n"


def entity_matrix(rep, export):
    native = [r for r in rep["views"] if r["kind"] == "native"]
    ents = sorted({e for r in native for e in r["entities"]})
    lines = [GEN + "# CasaRay V3 — entity matrix (native views)\n",
             "Authority: `docs/live/states_export_2026-09-05.txt` — proves an ID **exists**. "
             "Its availability column is a 05/09/26 snapshot, not today's state. Live state was "
             "NOT used to build V3 (offline build, owner instruction 01/11/26).\n",
             "| Entity | Friendly name (export) | Area (export) | At export | Used on |",
             "|---|---|---|---|---|"]
    for e in ents:
        x = export.get(e)
        used = ", ".join(r["path"] for r in native if e in r["entities"])
        if x:
            lines.append(f"| `{e}` | {x['name']} | {x['area']} | {x['availability']} | {used} |")
        else:
            lines.append(f"| `{e}` | **NOT IN EXPORT — unverified** | | | {used} |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    a = ap.parse_args()
    _, rep, stale = build(write=not a.check)
    if a.check:
        if stale:
            print("STALE (run the build):", *stale, sep="\n  ")
            return 1
        print("build outputs up to date")
        return 0
    for code, l in rep["locales"].items():
        print(f"{code:8} {l['output']}  views={l['views']}  fallback={len(l['fallback_keys'])}  "
              f"missing={len(l['missing_keys'])}")
    print("written:" if stale else "no changes", *stale, sep="\n  ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
